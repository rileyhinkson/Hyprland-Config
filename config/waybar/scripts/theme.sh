#!/usr/bin/env bash
# Accent colour for the whole setup. Black stays the base everywhere; this
# only swaps the secondary colour.
#
# The choice lives in ~/.config/theme/accent and everything else reads it from
# there -- rofi and waybar through generated snippets, the GTK panels and
# hyprland.lua by parsing it directly.
#
# Palette entries are  name|primary|stop stop stop...
# The optional stop list makes a multi-colour theme: it drives the window
# border, the lock screen and the Color widget, which are the surfaces that
# can draw a gradient. Everything else (rofi borders, panel borders) needs a
# single colour and uses the primary.
#
# Usage: theme.sh list          "name primary stops..." per line
#        theme.sh get           current primary hex
#        theme.sh current       current palette name
#        theme.sh set <name>    switch and reload everything
#        theme.sh apply         regenerate from the stored choice
#        theme.sh status        waybar JSON for the widget
set -uo pipefail

THEME_DIR="$HOME/.config/theme"
STATE="$THEME_DIR/accent"
ROFI_SNIPPET="$HOME/.config/rofi/accent.rasi"
WAYBAR_SNIPPET="$HOME/.config/waybar/accent.css"
HYPRLOCK="$HOME/.config/hypr/hyprlock.conf"
CAVA="$HOME/.config/cava/config"
DEFAULT_NAME="red"

PALETTE=(
    "white|#f0f0f0"
    "red|#ff3344"
    "orange|#ff8c1a"
    "yellow|#ffd633"
    "green|#00ff41"
    "sky|#33ccff"
    "blue|#3b82f6"
    "indigo|#6366f1"
    "violet|#a855f7"
    "pink|#ff4fa3"
    "rainbow|#a855f7|#ff3344 #ff8c1a #ffd633 #00ff41 #33ccff #a855f7"
    "trans|#5bcefa|#5bcefa #f5a9b8 #ffffff #f5a9b8 #5bcefa"
)

entry_of() {   # name -> "name|primary|stops"
    local entry
    for entry in "${PALETTE[@]}"; do
        [[ ${entry%%|*} == "$1" ]] && { printf '%s' "$entry"; return 0; }
    done
    return 1
}

field() { printf '%s' "$1" | cut -d'|' -f"$2"; }

rgb() {        # #rrggbb -> "r g b"
    local h=${1#\#}
    printf '%d %d %d' "0x${h:0:2}" "0x${h:2:2}" "0x${h:4:2}"
}

darken() {     # #rrggbb factor -> #rrggbb
    local r g b
    read -r r g b < <(rgb "$1")
    printf '#%02x%02x%02x' \
        "$(awk -v v="$r" -v f="$2" 'BEGIN{printf "%d", v*f}')" \
        "$(awk -v v="$g" -v f="$2" 'BEGIN{printf "%d", v*f}')" \
        "$(awk -v v="$b" -v f="$2" 'BEGIN{printf "%d", v*f}')"
}

luma() {       # #rrggbb -> perceived lightness, 0-100
    local r g b
    read -r r g b < <(rgb "$1")
    awk -v r="$r" -v g="$g" -v b="$b" \
        'BEGIN{printf "%d", (0.299*r + 0.587*g + 0.114*b) * 100 / 255}'
}

state_get() {  # key -> value
    [[ -r $STATE ]] && sed -n "s/^$1=//p" "$STATE" | head -1
}

current_name() {
    local name
    name=$(state_get name)
    printf '%s' "${name:-$DEFAULT_NAME}"
}

write_state() {   # name primary dark "stops"
    mkdir -p "$THEME_DIR"
    { echo "# Written by theme.sh -- use the waybar Color widget to change it."
      echo "name=$1"
      echo "accent=$2"
      echo "accent_dark=$3"
      echo "gradient=$4"
    } > "$STATE"
}

generate() {   # primary dark "stops"
    local accent=$1 dark=$2 stops=$3 r g b hex
    read -r r g b < <(rgb "$accent")

    mkdir -p "$(dirname "$ROFI_SNIPPET")" "$(dirname "$WAYBAR_SNIPPET")"
    # rofi can't draw gradients, so spread the stops across its elements:
    # border, prompt and selected row take the first, middle and last colour.
    local a1=$accent a2=$accent a3=$accent
    if [[ -n $stops ]]; then
        local -a uniq=()
        for hex in $stops; do
            [[ " ${uniq[*]-} " == *" $hex "* ]] || uniq+=("$hex")
        done
        a1=${uniq[0]}; a2=${uniq[$(( ${#uniq[@]} / 2 ))]}; a3=${uniq[-1]}
        # The selected row is a large filled block, so a near-white stop (the
        # white stripe in the trans flag) glares. Walk back to a colour that
        # can carry it.
        local i
        for (( i = ${#uniq[@]} - 1; i >= 0; i-- )); do
            if [[ $(luma "${uniq[$i]}") -le 85 ]]; then a3=${uniq[$i]}; break; fi
        done
    fi
    printf '/* generated by theme.sh */\n* {\n    accent:  %s;\n    accent2: %s;\n    accent3: %s;\n}\n' \
        "$a1" "$a2" "$a3" > "$ROFI_SNIPPET"

    { printf '/* generated by theme.sh */\n'
      printf '@define-color accent %s;\n' "$accent"
      printf '@define-color accent_soft rgba(%d, %d, %d, 0.15);\n' "$r" "$g" "$b"
      printf '@define-color accent_hover rgba(%d, %d, %d, 0.25);\n' "$r" "$g" "$b"
      if [[ -n $stops ]]; then
          # multi-colour theme: the Color widget wears the gradient itself
          printf '#custom-theme.theme { background-image: linear-gradient(90deg, %s); color: #101010; border-radius: 6px; padding: 0 10px; }\n' \
              "$(printf '%s' "$stops" | tr ' ' ',' | sed 's/,/, /g')"
      fi
    } > "$WAYBAR_SNIPPET"

    # hyprlock takes a gradient; keep the line shape so this stays a one-line edit
    local lock=""
    if [[ -n $stops ]]; then
        for hex in $stops; do lock+="rgba(${hex#\#}ee) "; done
    else
        lock="rgba(${accent#\#}ee) rgba(${dark#\#}ee) "
    fi
    [[ -w $HYPRLOCK ]] && sed -i -E "s|^(\s*outer_color = ).*|\1${lock}45deg|" "$HYPRLOCK"

    write_cava "$accent" "$stops"
}

cava_block() {   # primary "stops"
    local accent=$1 stops=$2 hex n=0
    echo "# >>> theme.sh (generated -- restart cava to apply; its r/c reload keys segfault)"
    echo "background = '#000000'"
    if [[ -n $stops ]]; then
        for hex in $stops; do n=$((n + 1)); done
        echo "gradient = 1"
        echo "gradient_count = $n"
        n=0
        for hex in $stops; do n=$((n + 1)); echo "gradient_color_$n = '$hex'"; done
    else
        echo "gradient = 0"
        echo "foreground = '$accent'"
    fi
    echo "# <<< theme.sh"
}

write_cava() {   # primary "stops"
    # cava has no include and no reload signal, so keep a marked block inside
    # its [color] section and replace that block in place.
    [[ -w $CAVA ]] || return 0
    local block tmp
    block=$(cava_block "$1" "$2")
    tmp=$(mktemp) || return 0
    awk -v block="$block" '
        /^# >>> theme\.sh/            { skip = 1 }
        skip && /^# <<< theme\.sh/    { skip = 0; next }
        skip                          { next }
                                      { print }
        /^\[color\]/ && !inserted     { print ""; print block; inserted = 1 }
    ' "$CAVA" > "$tmp" && mv "$tmp" "$CAVA"
}

reload() {
    # hyprctl keyword is a no-op under the Lua parser ("keyword can't work with
    # non-legacy parsers"), so reload instead -- hyprland.lua reads the accent
    # file at load and rebuilds the border gradient from it.
    hyprctl reload >/dev/null 2>&1
    pkill -SIGUSR2 waybar 2>/dev/null
}

apply_entry() {   # "name|primary|stops"
    local name primary stops dark
    name=$(field "$1" 1); primary=$(field "$1" 2); stops=$(field "$1" 3)
    [[ $stops == "$primary" ]] && stops=""      # cut -f3 echoes f2 when absent
    dark=$(darken "$primary" 0.45)
    write_state "$name" "$primary" "$dark" "$stops"
    generate "$primary" "$dark" "$stops"
}

case ${1:-status} in
    list)
        for entry in "${PALETTE[@]}"; do echo "$entry" | tr '|' ' '; done
        ;;
    get)     printf '%s' "$(state_get accent)" || printf '#ff3344' ;;
    current) current_name ;;
    set)
        [[ $# -ge 2 ]] || { echo "usage: theme.sh set <name>" >&2; exit 1; }
        entry=$(entry_of "$2") || { echo "unknown colour: $2" >&2; exit 1; }
        apply_entry "$entry"
        reload
        # cava 0.10.2 segfaults on its own reload keys ('r' and 'c') whenever the
        # colours change, so it has to be restarted to pick the theme up.
        hint="Accent: $2"
        pgrep -x cava >/dev/null && hint="$hint — restart cava (Ctrl+C) to apply there"
        notify-send -a "Theme" -i preferences-desktop-theme "$hint"
        ;;
    apply)
        entry=$(entry_of "$(current_name)") || entry=$(entry_of "$DEFAULT_NAME")
        apply_entry "$entry"
        ;;
    status)
        printf '{"text":"●  Color","tooltip":"Accent: %s\\n\\nClick to change the colour","class":"theme"}\n' \
            "$(current_name)"
        ;;
    *)
        echo "usage: theme.sh {list|get|current|set <name>|apply|status}" >&2; exit 1
        ;;
esac
